// The one lookup every caller needs: which districts belong to this state.
// Returns [] for an unknown or empty state so a caller can render an empty,
// disabled dropdown without special-casing.
export function districtsForState(stateName) {
  if (!stateName) return []
  const match = STATES.find((entry) => entry.name === stateName)
  return match ? match.districts : []
}

export function findState(stateName) {
  if (!stateName) return null
  return STATES.find((entry) => entry.name === stateName) || null
}

export const TOTAL_DISTRICTS = STATES.reduce((sum, entry) => sum + entry.districts.length, 0)
