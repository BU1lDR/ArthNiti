// The other three parts of the dictionary live in their own files purely for file
// size. Merging here means a lookup never has to know which file a key came from,
// and the per-key English fallback still works across all four.
const merge = (base, code) => ({
  ...base,
  ...(RESULT_STRINGS[code] || {}),
  ...(BACKEND_STRINGS[code] || {}),
  ...(SCHEME_STRINGS[code] || {}),
})

export const STRINGS = {
  en: merge(en, 'en'),
  hi: merge(hi, 'hi'),
  ta: merge(ta, 'ta'),
  te: merge(te, 'te'),
  ml: merge(ml, 'ml'),
  kn: merge(kn, 'kn'),
  mr: merge(mr, 'mr'),
  bn: merge(bn, 'bn'),
}

// How complete each language is, so the switcher can be honest about it rather
// than letting a user pick a language and then meet English.
export function coverageFor(code) {
  const total = Object.keys(STRINGS[FALLBACK_LANGUAGE]).length
  const done = Object.keys(STRINGS[code] || {}).length
  return { done, total, percent: Math.round((done / total) * 100) }
}
