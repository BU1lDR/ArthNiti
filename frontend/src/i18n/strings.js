// UI translations, keyed by language code.
//
// SCOPE: the whole interface is now translated, in four files that merge here.
//
//   strings.js       this file — chrome, landing page, the four journey steps
//   resultStrings.js labels and headings on the four result pages
//   backendStrings.js the prose the Python services generate
//   schemeStrings.js  the prose typed into schemes.json — 30 schemes' own words
//
// The split between the last two is by where the sentence was written, not by
// what it says: if a Python function builds it, it is in backendStrings.js; if it
// is typed into schemes.json, it is in schemeStrings.js. Both arrive through
// tBackend and behave identically at render.
//
// That last one closed the gap this comment used to describe. The services emit
// a stable code beside every sentence they build, and `tBackend` in
// LanguageContext turns the code into text — so advisory recommendations,
// business observations, the risk reason, scheme descriptions, eligibility and
// seasonality all follow the chosen language now, not just our own labels.
//
// Two things are still English regardless of language, and both are data rather
// than prose: scheme names (PMEGP, PMMY — proper nouns that appear that way on
// the official portal a user would be sent to) and the district names in
// data/indiaLocations.js (the Latin spelling printed on official documents).
// Digits and money stay Latin and 'en-IN'-grouped for the same reason.
//
// Any missing key falls back to English per key rather than per language, so a
// partially translated language is still a usable UI. A missing key in THIS file
// renders as its own dotted name, which is how a typo becomes visible on screen;
// a missing key in backendStrings.js instead falls back to the English sentence
// the backend sent, because a dotted name is worse than English prose.
//
// Wording aims to sound like how the language is actually spoken rather than a
// word-for-word rendering of the English, and uses everyday words over financial
// vocabulary throughout. Still unreviewed by a native speaker on the team. The
// highest-stakes strings are the money ones — anything that tells a user how
// much they need to arrange or how much is left over.

